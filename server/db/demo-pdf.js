'use strict';

/**
 * Tiny dependency-free PDF writer used ONLY to create realistic demo files
 * during seeding (so the document viewer and blueprint viewer have something
 * to display). It is not used in production request handling.
 */

function esc(text) {
  return String(text).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function build(contentLines, { width = 842, height = 595 } = {}) {
  const content = contentLines.join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${width} ${height}] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>`,
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((obj, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (const off of offsets) pdf += `${String(off).padStart(10, '0')} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

function text(x, y, str, size = 11, bold = false) {
  return `BT /${bold ? 'F2' : 'F1'} ${size} Tf 1 0 0 1 ${x} ${y} Tm (${esc(str)}) Tj ET`;
}

function line(x1, y1, x2, y2, w = 1, dash = false) {
  return `${w} w ${dash ? '[6 4] 0 d' : '[] 0 d'} ${x1} ${y1} m ${x2} ${y2} l S`;
}

function rect(x, y, w, h, lw = 1) {
  return `${lw} w ${x} ${y} ${w} ${h} re S`;
}

/** Land-title style document (letter/A4 portrait-ish) */
function titleDocument({ documentName, ownerName, details = [], note }) {
  const w = 595;
  const h = 842;
  const lines = [
    rect(36, 36, w - 72, h - 72, 1),
    rect(40, 40, w - 80, h - 80, 0.5),
    text(60, h - 90, 'REPUBLIC OF THE PHILIPPINES', 13, true),
    text(60, h - 108, 'PROVINCE OF PAMPANGA', 11),
    text(60, h - 126, documentName.toUpperCase(), 16, true),
    line(60, h - 140, w - 60, h - 140, 1.2),
    text(60, h - 170, 'This demo document was generated for the', 10),
    text(60, h - 184, 'Land Surveying Management System sample dataset.', 10),
    text(60, h - 220, `Registered owner / title holder: ${ownerName}`, 11, true),
  ];

  let y = h - 260;
  for (const d of details) {
    lines.push(text(60, y, `${d.label}:`, 10, true));
    lines.push(text(220, y, String(d.value ?? '—'), 10));
    y -= 22;
  }

  lines.push(line(60, 150, w - 60, 150, 0.6, true));
  lines.push(text(60, 128, note || 'DEMO COPY — not a valid legal document.', 9));
  lines.push(text(60, 100, 'Generated by the surveying office for testing purposes only.', 9));
  lines.push(text(60, 84, 'Only the Register of Deeds can certify land title authenticity.', 9, true));

  return build(lines, { width: w, height: h });
}

/** Lot plan / survey blueprint drawing */
function lotPlan({ title, lotNo, location, area, surveyor, date, pointCount = 6, released = false }) {
  const w = 842;
  const h = 595;
  const m = 28;
  const lines = [];

  lines.push(rect(m, m, w - m * 2, h - m * 2, 1.4));
  lines.push(rect(m + 8, m + 8, w - m * 2 - 16, h - m * 2 - 16, 0.5));

  lines.push(text(m + 24, h - m - 34, title.toUpperCase(), 15, true));
  lines.push(text(m + 24, h - m - 52, 'SURVEY PLAN PREPARED FOR RECORD AND REVIEW', 8));

  // drawing area
  const dx = 150;
  const dy = 120;
  const dw = 420;
  const dh = 300;
  lines.push(rect(dx, dy, dw, dh, 0.8, true));

  // polygon
  const cx = dx + dw / 2;
  const cy = dy + dh / 2;
  const r = Math.min(dw, dh) / 2 - 40;
  const pts = [];
  for (let i = 0; i < pointCount; i += 1) {
    const angle = (Math.PI * 2 * i) / pointCount - Math.PI / 2;
    const jitter = i % 2 === 0 ? 1 : 0.86;
    pts.push([cx + Math.cos(angle) * r * jitter, cy + Math.sin(angle) * r * jitter]);
  }
  lines.push('0.9 w [ ] 0 d');
  lines.push(`${pts.map(([x, y], i) => `${i === 0 ? '' : ''}${x.toFixed(1)} ${y.toFixed(1)} ${i === 0 ? 'm' : 'l'}`).join(' ')} h S`);
  for (let i = 0; i < pts.length; i += 1) {
    const [x, y] = pts[i];
    lines.push(`0.6 w ${x.toFixed(1)} ${y.toFixed(1)} m ${x.toFixed(1)} ${y.toFixed(1)} l S`);
    lines.push(text(x + 5, y + 4, `${i + 1}`, 8, true));
  }

  // north arrow
  lines.push(`1 w ${dx + 24} ${dy + dh - 20} m ${dx + 24} ${dy + dh - 70} l S`);
  lines.push(`1 w ${dx + 24} ${dy + dh - 70} m ${dx + 16} ${dy + dh - 56} l S`);
  lines.push(`1 w ${dx + 24} ${dy + dh - 70} m ${dx + 32} ${dy + dh - 56} l S`);
  lines.push(text(dx + 16, dy + dh - 86, 'N', 11, true));

  // scale bar
  lines.push(line(dx + 20, dy + 22, dx + 170, dy + 22, 1));
  lines.push(line(dx + 20, dy + 17, dx + 20, dy + 27, 1));
  lines.push(line(dx + 170, dy + 17, dx + 170, dy + 27, 1));
  lines.push(text(dx + 20, dy + 6, '0', 7));
  lines.push(text(dx + 156, dy + 6, '50 m', 7));

  // title block
  const tbX = 596;
  const tbY = 100;
  const tbW = 218;
  const tbH = 380;
  lines.push(rect(tbX, tbY, tbW, tbH, 1.2));
  const rows = [
    ['LOT NO.', lotNo],
    ['LOCATION', location],
    ['AREA', area],
    ['SURVEYOR', surveyor],
    ['DATE', date],
    ['STATUS', released ? 'APPROVED FOR RELEASE' : 'DRAFT — NOT FOR RELEASE'],
    ['REVISION', '1'],
    ['PROJECT', title],
  ];
  let ty = tbY + tbH - 34;
  for (const [k, v] of rows) {
    lines.push(text(tbX + 14, ty, k, 7, true));
    const value = String(v ?? '');
    const chunks = value.match(/.{1,30}/g) || [''];
    chunks.slice(0, 2).forEach((chunk, idx) => lines.push(text(tbX + 14, ty - 14 - idx * 11, chunk, 9)));
    lines.push(line(tbX, ty - 42, tbX + tbW, ty - 42, 0.3, true));
    ty -= 46;
  }

  lines.push(text(m + 24, m + 26, 'This drawing is a digital sample generated for system testing.', 8));
  lines.push(
    text(
      m + 24,
      m + 14,
      'It is NOT an official cadastral survey plan and has no legal standing until verified and approved by a licensed Geodetic Engineer.',
      7,
      true,
    ),
  );

  return build(lines, { width: w, height: h });
}

module.exports = { build, titleDocument, lotPlan };

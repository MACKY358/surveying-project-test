let fileSeq = 0;
function storeFile(dir, buffer, ext) {
  fileSeq += 1;
  const name = `${Date.now()}-${String(fileSeq).padStart(3, '0')}-demo.${ext}`;
  fs.writeFileSync(path.join(dir, name), buffer);
  return name;
}

